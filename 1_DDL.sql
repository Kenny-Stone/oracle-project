create or replace PROCEDURE PROC_BOOK_TICKET (
    p_user_id   IN NUMBER,
    p_ticket_id IN NUMBER,
    p_quantity  IN NUMBER
) AS
    v_event_id        NUMBER;
    v_capacity        NUMBER;
    v_tickets_booked  NUMBER;
    v_tickets_left    NUMBER;
    v_user_email      VARCHAR2(100);
    v_event_title     VARCHAR2(100);
    v_booking_id      NUMBER;
BEGIN
    -- 1. Retrieve Event details (ID, Capacity, Title)
    SELECT event_id INTO v_event_id 
      FROM Ticket 
     WHERE ticket_id = p_ticket_id;
     
    SELECT capacity, title INTO v_capacity, v_event_title 
      FROM Event 
     WHERE event_id = v_event_id;

    -- 2. Retrieve User Email for notification
    SELECT email INTO v_user_email 
      FROM "User" 
     WHERE user_id = p_user_id;

    -- 3. Calculate remaining tickets
    SELECT NVL(SUM(b.quantity), 0) INTO v_tickets_booked
      FROM Booking b
      JOIN Ticket t ON b.ticket_id = t.ticket_id
     WHERE t.event_id = v_event_id;

    v_tickets_left := v_capacity - v_tickets_booked;

    -- 4. Validations
    IF p_quantity <= 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Quantity must be greater than zero.');
    ELSIF v_tickets_left < p_quantity THEN
        RAISE_APPLICATION_ERROR(-20002, 'Booking failed: Not enough tickets available. Only ' || v_tickets_left || ' left.');
    ELSE
        -- 5. Insert Booking and capture the generated booking_id
        INSERT INTO Booking (quantity, user_id, ticket_id) 
        VALUES (p_quantity, p_user_id, p_ticket_id)
        RETURNING booking_id INTO v_booking_id;

        -- 6. Send Email Notification via APEX_MAIL
        IF v_user_email IS NOT NULL THEN
            APEX_MAIL.SEND(
                p_to   => v_user_email,
                p_from => 'noreply@atu.edu.gh',
                p_subj => 'Booking Confirmation - ' || v_event_title,
                p_body => 'Hello,' || CHR(10) || CHR(10) ||
                          'Your booking (ID: ' || v_booking_id || ') for "' || v_event_title || 
                          '" has been successfully created.' || CHR(10) ||
                          'Quantity: ' || p_quantity || CHR(10) || CHR(10) ||
                          'Thank you for using ATU ETMS!'
            );
            
            -- Push queued mail immediately
            APEX_MAIL.PUSH_QUEUE();
        END IF;

        COMMIT;
    END IF;
END PROC_BOOK_TICKET;
/
create or replace PROCEDURE PROC_CREATE_EVENT (
    p_title      IN VARCHAR2,
    p_location   IN VARCHAR2,
    p_event_date IN DATE,
    p_capacity   IN NUMBER
) AS
BEGIN
    -- Business Rule Validation: Check capacity and date
    IF p_capacity <= 0 THEN
        RAISE_APPLICATION_ERROR(-20005, 'Event capacity must be greater than zero.');
    ELSIF p_event_date < SYSDATE THEN
        RAISE_APPLICATION_ERROR(-20006, 'Event date cannot be set in the past.');
    ELSE
        -- Insert the event record
        INSERT INTO Event (
            event_id,
            title,
            location,
            event_date,
            capacity
        ) VALUES (
            NULL, -- Handled by database identity or sequence
            p_title,
            p_location,
            p_event_date,
            p_capacity
        );
        
        COMMIT;
        DBMS_OUTPUT.PUT_LINE('Event created successfully!');
    END IF;
END PROC_CREATE_EVENT;
