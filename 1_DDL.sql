create or replace FUNCTION app_user_auth (
    p_username IN VARCHAR2,
    p_password IN VARCHAR2
) RETURN BOOLEAN IS
    v_count NUMBER;
BEGIN
    SELECT COUNT(*)
      INTO v_count
      FROM "User"
     WHERE UPPER("USERNAME") = UPPER(p_username)
       AND "PASSWORD_HASH" = p_password;

    IF v_count > 0 THEN
        RETURN TRUE;
    ELSE
        RETURN FALSE;
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        RETURN FALSE;
END;
/
create or replace FUNCTION func_authenticate_user (
    p_username IN VARCHAR2,
    p_password IN VARCHAR2
) RETURN BOOLEAN
IS
    v_stored_hash VARCHAR(255);
BEGIN
    SELECT password_hash
    INTO v_stored_hash
    FROM "User"
    WHERE LOWER(TRIM(username)) = LOWER(TRIM(p_username))
    OR LOWER(TRIM(email)) = LOWER(TRIM(p_username));

    IF v_stored_hash = func_hash_password(p_password) THEN
        RETURN TRUE;
    ELSE
        RETURN FALSE;
    END IF;

EXCEPTION
    WHEN OTHERS THEN
        RETURN FALSE;
END func_authenticate_user;
/
create or replace FUNCTION func_hash_password (
    p_password IN VARCHAR2
) RETURN VARCHAR2
IS
    v_hash VARCHAR(255);
BEGIN
    IF p_password IS NULL THEN
        RETURN NULL;
    END IF;

    SELECT LOWER(RAWTOHEX(STANDARD_HASH(p_password,'SHA256')))
        INTO v_hash
        FROM DUAL;

    RETURN v_hash;
END func_hash_password;
/
create or replace FUNCTION FUNC_TOTAL_REVENUE (
    p_event_id IN NUMBER
) RETURN NUMBER AS
    v_total_revenue NUMBER := 0;
BEGIN
    SELECT NVL(SUM(b.quantity * t.price), 0) INTO v_total_revenue
    FROM Booking b
    JOIN Ticket t ON b.ticket_id = t.ticket_id
    WHERE t.event_id = p_event_id;

    RETURN v_total_revenue;
EXCEPTION
    WHEN OTHERS THEN
        RETURN 0;
END FUNC_TOTAL_REVENUE;
/




























